def test_a_member_scope_that_is_not_what_the_documents_name_fails_the_agreement_check(
    tmp_path: Path, capsys
) -> None:
    """The verifier fails the agreement check when the member scope has too much or too little.

    The member scope of a generated package is the design nodes, the outcomes
    and nothing else: the check named agreement is passed. Two private copies
    change the evidence manifest only. In the first, the member scope holds
    one name more that no document names. In the second, one design node is
    missing from the member scope. For each copy the agreement check is
    failed and the root check is still passed.

    :verifies: SEG-SREQ-267
    :test-id: SEG-TS-155
    """
    sealed = seal(tmp_path, capsys)
    assert statuses(_verify(sealed.package))["agreement"] == "passed"
    node = read(sealed.package, "design_consistency_proof")["nodeManifest"][0]["id"]

    def more(body: dict) -> None:
        body["memberScope"].append("NO-SUCH-NODE")

    def less(body: dict) -> None:
        body["memberScope"].remove(node)

    for label, tamper in (("more", more), ("less", less)):
        copy = copy_package(sealed.package, tmp_path, label)
        edit(copy, "evidence_manifest", tamper)
        found = statuses(_verify(copy))
        assert found["agreement"] == "failed", label
        assert found["root"] == "passed", label


def test_a_coverage_report_that_lists_an_unready_edge_fails_the_unblocked_check(
    tmp_path: Path, capsys
) -> None:
    """The verifier fails the unblocked check when the report lists an unready edge.

    A private copy of a generated package lists one design edge as pending in
    the unready edges of its coverage report, and keeps the flag that says
    the scope is not blocked. For the copy the check named unblocked is
    failed and the root check is still passed. The untouched package passes.

    :verifies: SEG-SREQ-268
    :test-id: SEG-TS-156
    """
    sealed = seal(tmp_path, capsys)
    assert statuses(_verify(sealed.package))["unblocked"] == "passed"
    edge = read(sealed.package, "design_consistency_proof")["designEdges"][0]
    copy = copy_package(sealed.package, tmp_path, "unready")
    edit(
        copy,
        "coverage_report",
        lambda body: body["unreadyEdges"].append({**edge, "state": "pending"}),
    )

    found = statuses(_verify(copy))

    assert found["unblocked"] == "failed"
    assert found["root"] == "passed"


